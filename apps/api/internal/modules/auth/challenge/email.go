// ForTransaction refuses zero values, expired proofs and other or completed
// transactions. Downstream operations must accept the opaque proof itself and
// perform all identity and authorization writes using this same transaction;
// the exported details alone are never an authentication credential.
func (v *VerifiedEmail) ForTransaction(ctx context.Context, tx *sql.Tx) (VerifiedEmailDetails, error) {
	if v == nil || ctx == nil || tx == nil || v.tx != tx || v.now == nil ||
		v.index == [32]byte{} || len(v.ciphertext) == 0 || v.keyID == "" || v.fingerprint == [32]byte{} {
		return VerifiedEmailDetails{}, ErrChallengeStore
	}
	now := v.now().UTC()
	if now.IsZero() || !v.expiresAt.After(now) {
		return VerifiedEmailDetails{}, ErrChallengeStore
	}
	if _, err := domain.VerifyDeviceProof(v.proof, v.publicKey, v.expectation, now, v.policy); err != nil {
		return VerifiedEmailDetails{}, ErrChallengeStore
	}
	var live int
	if err := tx.QueryRowContext(ctx, "SELECT 1").Scan(&live); err != nil || live != 1 {
		return VerifiedEmailDetails{}, ErrChallengeStore
	}
	return VerifiedEmailDetails{Index: v.index, Ciphertext: append([]byte(nil), v.ciphertext...), KeyID: v.keyID,
		Fingerprint: v.fingerprint, PublicKey: v.publicKey}, nil
}

// ReceiptScope returns only the protected lookup scope for a challenge. It is
// not a proof of identity and must not be exposed as an account lookup. The
// receipt store must check the challenge and scope again under its row locks.
func (s *Store) ReceiptScope(ctx context.Context, tx *sql.Tx, challengeID string) ([32]byte, bool, error) {
	var scope [32]byte
	if s == nil || s.identities == nil || ctx == nil || tx == nil || !opaque(challengeID, 22, 128) || s.checkEmailEpoch(ctx, tx) != nil {
		return scope, false, ErrChallengeStore
	}
	var stored []byte
	err := tx.QueryRowContext(ctx, `SELECT email_index FROM auth_email_login_challenge WHERE challenge_id = ?`, challengeID).Scan(&stored)
	if errors.Is(err, sql.ErrNoRows) {
		return scope, false, nil
	}
	if err != nil || len(stored) != len(scope) {
		return scope, false, ErrChallengeStore
	}
	copy(scope[:], stored)
	if scope == ([32]byte{}) {
		return scope, false, ErrChallengeStore
	}
	return scope, true, nil
}

// ReceiptProof is a transaction-bound revalidation of a previously consumed
// device proof. It cannot issue a session: callers must also match the exact
// request to a live encrypted receipt and independently recheck current user,
// identity, device, session or approval authorization before releasing it.
type ReceiptProof struct {
	store       *Store
	tx          *sql.Tx
	scope       [32]byte
	challengeID string
	compact     string
}

type ReceiptProofDetails struct {
	Scope       [32]byte
	Fingerprint [32]byte
	ChallengeID string
}

func (ReceiptProof) String() string                      { return "EmailReceiptProof{redacted}" }
func (ReceiptProof) GoString() string                    { return "EmailReceiptProof{redacted}" }
func (ReceiptProof) MarshalJSON() ([]byte, error)        { return nil, ErrChallengeStore }
func (ReceiptProof) LogValue() slog.Value                { return slog.StringValue("EmailReceiptProof{redacted}") }
func (ReceiptProofDetails) String() string               { return "EmailReceiptProofDetails{redacted}" }
func (ReceiptProofDetails) GoString() string             { return "EmailReceiptProofDetails{redacted}" }
func (ReceiptProofDetails) MarshalJSON() ([]byte, error) { return nil, ErrChallengeStore }
func (ReceiptProofDetails) LogValue() slog.Value {
	return slog.StringValue("EmailReceiptProofDetails{redacted}")
}

// VerifyReceiptProof revalidates the original signed proof and its existing
// replay marker in this transaction. It may inspect an older challenge after a new one
// replaces the slot; it never accepts that old challenge for a new login.
// Call only after reserving the corresponding exact-request receipt.
func (s *Store) VerifyReceiptProof(ctx context.Context, tx *sql.Tx, scope [32]byte, challengeID, compact string) (*ReceiptProof, error) {
	if _, err := s.verifyReceiptProof(ctx, tx, scope, challengeID, compact); err != nil {
		return nil, err
	}
	return &ReceiptProof{store: s, tx: tx, scope: scope, challengeID: challengeID, compact: compact}, nil
}

// ForTransaction repeats the check after any further lock waits and detects
// changes made by this transaction itself. It does not check a receipt or grant
// access to credentials. The originating transaction must still be active.
func (p *ReceiptProof) ForTransaction(ctx context.Context, tx *sql.Tx) (ReceiptProofDetails, error) {
	if p == nil || p.store == nil || tx == nil || p.tx != tx {
		return ReceiptProofDetails{}, ErrChallengeStore
	}
	return p.store.verifyReceiptProof(ctx, tx, p.scope, p.challengeID, p.compact)
}

func (s *Store) verifyReceiptProof(ctx context.Context, tx *sql.Tx, scope [32]byte, challengeID, compact string) (ReceiptProofDetails, error) {
	var details ReceiptProofDetails
	if s == nil || s.replay == nil || s.identities == nil || s.now == nil || ctx == nil || tx == nil ||
		scope == ([32]byte{}) || !opaque(challengeID, 22, 128) || s.checkEmailEpoch(ctx, tx) != nil {
		return details, ErrChallengeStore
	}
	// Preserve the shared identity epoch -> slot -> challenge -> replay order.
	var activeID []byte
	err := tx.QueryRowContext(ctx, `SELECT challenge_id FROM auth_email_login_slot WHERE email_index = ? FOR UPDATE`, scope[:]).Scan(&activeID)
	if errors.Is(err, sql.ErrNoRows) {
		return details, ErrReceiptProofRejected
	}
	if err != nil || !opaque(string(activeID), 22, 128) {
		return details, ErrChallengeStore
	}
	var storedIndex, ciphertext, keyID, nonce, fingerprint []byte
	var x, y, createdRaw, expiresRaw string
	var maxLifetimeNS, clockSkewNS int64
	err = tx.QueryRowContext(ctx, `SELECT email_index, email_ciphertext, email_key_id, nonce, public_x, public_y, key_fingerprint,
		proof_max_lifetime_ns, proof_clock_skew_ns, CAST(created_at AS CHAR), CAST(expires_at AS CHAR)
		FROM auth_email_login_challenge WHERE challenge_id = ? FOR UPDATE`, challengeID).
		Scan(&storedIndex, &ciphertext, &keyID, &nonce, &x, &y, &fingerprint, &maxLifetimeNS, &clockSkewNS, &createdRaw, &expiresRaw)
	if errors.Is(err, sql.ErrNoRows) {
		return details, ErrReceiptProofRejected
	}
	if err != nil || len(storedIndex) != len(scope) || !hmac.Equal(storedIndex, scope[:]) || len(fingerprint) != 32 || !opaque(string(nonce), 43, 256) {
		return details, ErrChallengeStore
	}
	currentKeyID, _, err := s.identities.KeyEpoch()
	if err != nil || string(keyID) != currentKeyID {
		return details, ErrChallengeStore
	}
	if _, err := s.identities.Open(scope, ciphertext); err != nil {
		return details, ErrChallengeStore
	}
	// The original challenge deadline controlled its first consumption. A
	// receipt retry does not consume it again; the signed proof and receipt
	// must still be live, and current authorization must be checked separately.
	created, createdErr := time.Parse("2006-01-02 15:04:05.999999", createdRaw)
	expires, expiresErr := time.Parse("2006-01-02 15:04:05.999999", expiresRaw)
	policy := domain.ProofPolicy{MaxLifetime: time.Duration(maxLifetimeNS), ClockSkew: time.Duration(clockSkewNS)}
	if createdErr != nil || expiresErr != nil || !expires.After(created) || expires.Sub(created) > 30*time.Minute || !domain.ValidProofPolicy(policy) || !domain.ValidProofPolicy(s.policy.DeviceProof) {
		return details, ErrChallengeStore
	}
	if s.policy.DeviceProof.MaxLifetime < policy.MaxLifetime {
		policy.MaxLifetime = s.policy.DeviceProof.MaxLifetime
	}
	if s.policy.DeviceProof.ClockSkew < policy.ClockSkew {
		policy.ClockSkew = s.policy.DeviceProof.ClockSkew
	}
	key := domain.DevicePublicJWK{Kty: "EC", Crv: "P-256", X: x, Y: y}
	actualFingerprint, err := domain.DeviceKeyFingerprint(key)
	if err != nil || !hmac.Equal(actualFingerprint[:], fingerprint) {
		return details, ErrChallengeStore
	}
	expected := domain.ProofExpectation{Purpose: "email_login", ResourceID: challengeID, Nonce: string(nonce)}
	now := s.now().UTC()
	if now.IsZero() || now.Before(created) {
		return details, ErrChallengeStore
	}
	proof, err := domain.VerifyDeviceProof(compact, key, expected, now, policy)
	if err != nil {
		return details, ErrReceiptProofRejected
	}
	if err := s.replay.EnsureConsumed(ctx, tx, actualFingerprint, proof, now); err != nil {
		if errors.Is(err, repository.ErrProofNotConsumed) {
			return details, ErrReceiptProofRejected
		}
		return details, ErrChallengeStore
	}
	// The marker lookup may have waited. Revalidate the signed proof using a
	// fresh clock reading before returning even this non-authorizing handle.
	finished := s.now().UTC()
	if finished.IsZero() || finished.Before(created) {
		return details, ErrChallengeStore
	}
	if _, err := domain.VerifyDeviceProof(compact, key, expected, finished, policy); err != nil {
		return details, ErrReceiptProofRejected
	}
	return ReceiptProofDetails{Scope: scope, Fingerprint: actualFingerprint, ChallengeID: challengeID}, nil
}

// Attempt returns the same rejected result for unknown, expired, superseded,
// exhausted, invalid and replayed challenges. Callers must enforce independent
// email/IP/device/global rate limits before exposing any HTTP operation.
func (s *Store) Attempt(ctx context.Context, tx *sql.Tx, input AttemptInput) (AttemptResult, error) {
	rejected := AttemptResult{}
	if s == nil || s.hasher == nil || s.replay == nil || s.identities == nil || s.now == nil || ctx == nil || tx == nil ||
		!opaque(input.ChallengeID, 22, 128) {
		return rejected, ErrChallengeStore
	}
	now := s.now().UTC()
	if now.IsZero() {
		return rejected, ErrChallengeStore
	}
	if err := s.checkEmailEpoch(ctx, tx); err != nil {
		return rejected, ErrChallengeStore
	}
	var emailIndex []byte
	err := tx.QueryRowContext(ctx, `SELECT email_index FROM auth_email_login_challenge WHERE challenge_id = ?`, input.ChallengeID).Scan(&emailIndex)
	if errors.Is(err, sql.ErrNoRows) {
		return rejected, nil
	}
	if err != nil || len(emailIndex) != 32 {
		return rejected, ErrChallengeStore
	}
	var activeID []byte
	err = tx.QueryRowContext(ctx, `SELECT challenge_id FROM auth_email_login_slot WHERE email_index = ? FOR UPDATE`, emailIndex).Scan(&activeID)
	if errors.Is(err, sql.ErrNoRows) || err == nil && string(activeID) != input.ChallengeID {
		return rejected, nil
	}
	if err != nil {
		return rejected, ErrChallengeStore
	}
	var storedIndex, ciphertext, keyID, nonce, fingerprint, digest []byte
	var x, y string
	var attempts, maxAttempts int
	var maxLifetimeNS, clockSkewNS int64
	var createdRaw, expiresRaw string
	var consumed bool
	err = tx.QueryRowContext(ctx, `SELECT email_index, email_ciphertext, email_key_id, nonce, public_x, public_y, key_fingerprint, code_digest, attempts, max_attempts, proof_max_lifetime_ns, proof_clock_skew_ns, CAST(created_at AS CHAR), CAST(expires_at AS CHAR), consumed_at IS NOT NULL
        FROM auth_email_login_challenge WHERE challenge_id = ? FOR UPDATE`, input.ChallengeID).
		Scan(&storedIndex, &ciphertext, &keyID, &nonce, &x, &y, &fingerprint, &digest, &attempts, &maxAttempts, &maxLifetimeNS, &clockSkewNS, &createdRaw, &expiresRaw, &consumed)
	if errors.Is(err, sql.ErrNoRows) {
		return rejected, nil
	}
	if err != nil || len(storedIndex) != 32 || !hmac.Equal(emailIndex, storedIndex) || len(fingerprint) != 32 || len(digest) != 32 ||
		maxAttempts < 1 || maxAttempts > 10 || attempts < 0 || attempts > maxAttempts {
		return rejected, ErrChallengeStore
	}
	proofPolicy := domain.ProofPolicy{MaxLifetime: time.Duration(maxLifetimeNS), ClockSkew: time.Duration(clockSkewNS)}
	if !domain.ValidProofPolicy(proofPolicy) {
		return rejected, ErrChallengeStore
	}
	if s.policy.DeviceProof.MaxLifetime < proofPolicy.MaxLifetime {
		proofPolicy.MaxLifetime = s.policy.DeviceProof.MaxLifetime
	}
	if s.policy.DeviceProof.ClockSkew < proofPolicy.ClockSkew {
		proofPolicy.ClockSkew = s.policy.DeviceProof.ClockSkew
	}
	created, createdErr := time.Parse("2006-01-02 15:04:05.999999", createdRaw)
	expires, expiresErr := time.Parse("2006-01-02 15:04:05.999999", expiresRaw)
	if createdErr != nil || expiresErr != nil || !expires.After(created) || expires.Sub(created) > 30*time.Minute {
		return rejected, ErrChallengeStore
	}
	// A stricter deployed policy immediately applies to already-issued
	// challenges; relaxing it never extends their original limits.
	if policyExpiry := created.Add(s.policy.ChallengeTTL); policyExpiry.Before(expires) {
		expires = policyExpiry
	}
	if s.policy.MaxAttempts < maxAttempts {
		maxAttempts = s.policy.MaxAttempts
	}
	// Slot and challenge locks can block long enough for a challenge or proof
	// to expire. Never validate them against a timestamp taken before the wait.
	now = s.now().UTC()
	if now.IsZero() {
		return rejected, ErrChallengeStore
	}
	if consumed || attempts >= maxAttempts || now.Before(created) || !expires.After(now) {
		return rejected, nil
	}
	var index [32]byte
	copy(index[:], emailIndex)
	currentKeyID, _, err := s.identities.KeyEpoch()
	if err != nil || string(keyID) != currentKeyID {
		return rejected, ErrChallengeStore
	}
	if _, err := s.identities.Open(index, ciphertext); err != nil {
		return rejected, ErrChallengeStore
	}
	key := domain.DevicePublicJWK{Kty: "EC", Crv: "P-256", X: x, Y: y}
	actualFingerprint, err := domain.DeviceKeyFingerprint(key)
	if err != nil || !hmac.Equal(actualFingerprint[:], fingerprint) {
		return rejected, ErrChallengeStore
	}
	expectation := domain.ProofExpectation{Purpose: "email_login", ResourceID: input.ChallengeID, Nonce: string(nonce)}
	proof, err := domain.VerifyDeviceProof(input.DeviceProof, key, expectation, now, proofPolicy)
	if err != nil {
		return rejected, nil
	}
	// Every valid signed attempt consumes its JTI, including an incorrect
	// code. A caller must commit or roll back the replay marker and the
	// wrong-code counter together; the marker alone never authenticates.
	if err := s.replay.Consume(ctx, tx, actualFingerprint, proof, now); err != nil {
		if errors.Is(err, repository.ErrProofAlreadyUsed) {
			return rejected, nil
		}
		return rejected, ErrChallengeStore
	}
	// Inserting the replay marker may itself wait on a concurrent transaction.
	// If validity elapsed, require rollback so no stale marker or count commits.
	finished := s.now().UTC()
	if finished.IsZero() || finished.Before(created) || !expires.After(finished) {
		return rejected, ErrChallengeStore
	}
	if _, err := domain.VerifyDeviceProof(input.DeviceProof, key, expectation, finished, proofPolicy); err != nil {
		return rejected, ErrChallengeStore
	}
	now = finished
	correct, err := s.hasher.Verify(input.ChallengeID, "email_login", input.Code, digest)
	if err != nil || !correct {
		if _, err := tx.ExecContext(ctx, `UPDATE auth_email_login_challenge SET attempts = attempts + 1 WHERE challenge_id = ?`, input.ChallengeID); err != nil {
			return rejected, ErrChallengeStore
		}
		return AttemptResult{Changed: true}, nil
	}
	result, err := tx.ExecContext(ctx, `UPDATE auth_email_login_challenge SET consumed_at = ? WHERE challenge_id = ? AND consumed_at IS NULL`, sqlUTC(now), input.ChallengeID)
	if err != nil {
		return rejected, ErrChallengeStore
	}
	if count, err := result.RowsAffected(); err != nil || count != 1 {
		return rejected, ErrChallengeStore
	}
	verified := &VerifiedEmail{tx: tx, index: index, ciphertext: append([]byte(nil), ciphertext...),
		keyID: currentKeyID, fingerprint: actualFingerprint, publicKey: key, expiresAt: expires,
		proof: input.DeviceProof, expectation: expectation, policy: proofPolicy, now: s.now}
	return AttemptResult{Verified: true, Changed: true, Proof: verified}, nil
}

func (s *Store) checkEmailEpoch(ctx context.Context, tx *sql.Tx) error {
	_, expected, err := s.identities.KeyEpoch()
	if err != nil {
		return ErrChallengeStore
	}
	var stored []byte
	err = tx.QueryRowContext(ctx, `SELECT key_tag FROM auth_email_identity_key_epoch WHERE slot = 1 FOR SHARE`).Scan(&stored)
	if err != nil || !hmac.Equal(stored, expected[:]) {
		return ErrChallengeStore
	}
	return nil
}

// DATETIME has no timezone. Supplying and reading explicit UTC strings avoids
// silently changing deadlines when driver connections use different loc values.
func sqlUTC(value time.Time) string {
	return value.UTC().Truncate(time.Microsecond).Format("2006-01-02 15:04:05.000000")
}

func opaque(value string, min, max int) bool {
	if len(value) < min || len(value) > max {
		return false
	}
	for _, c := range value {
		if !(c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '_' || c == '-') {
			return false
		}
	}
	return true
}
