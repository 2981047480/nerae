// WireBody returns a copy of the response body for a trusted transport adapter.
// Do not log it: it contains the one-time challenge nonce.
func (r ChallengeRequestResult) WireBody() []byte { return append([]byte(nil), r.body...) }

func NewChallengeRequestIssuer(challenges *challenge.Store, outbox *Outbox, identities *domain.EmailIdentityProtector, limiter *ratelimit.Limiter, keys RequestKeyConfig) (*ChallengeRequestIssuer, error) {
	if challenges == nil || outbox == nil || identities == nil || limiter == nil || outbox.identities != identities ||
		!validOutboxKeyID(keys.KeyID) || keys.Retention < time.Minute || keys.Retention > 24*time.Hour || keys.Retention%time.Microsecond != 0 || keys.CodeDigits < 6 || keys.CodeDigits > 10 ||
		len(keys.IdempotencyHMACKey) != 32 || len(keys.RequestHMACKey) != 32 || len(keys.ResponseAESKey) != 32 ||
		subtle.ConstantTimeCompare(keys.IdempotencyHMACKey, keys.RequestHMACKey) == 1 ||
		subtle.ConstantTimeCompare(keys.IdempotencyHMACKey, keys.ResponseAESKey) == 1 ||
		subtle.ConstantTimeCompare(keys.RequestHMACKey, keys.ResponseAESKey) == 1 {
		return nil, ErrChallengeRequest
	}
	i := &ChallengeRequestIssuer{challenges: challenges, outbox: outbox, identities: identities, limiter: limiter,
		keyID: keys.KeyID, retention: keys.Retention, codeDigits: keys.CodeDigits}
	copy(i.idemKey[:], keys.IdempotencyHMACKey)
	copy(i.requestKey[:], keys.RequestHMACKey)
	copy(i.cipherKey[:], keys.ResponseAESKey)
	return i, nil
}

// InitializeKey explicitly binds the anonymous request keys to the database.
// It is a deployment/bootstrap operation, not a per-request lazy initializer.
// The caller owns the transaction and must stop old writers before recovery.
func (i *ChallengeRequestIssuer) InitializeKey(ctx context.Context, tx *sql.Tx) error {
	if i == nil || ctx == nil || tx == nil || i.outbox == nil {
		return ErrChallengeRequest
	}
	if _, err := i.outbox.LockEpochs(ctx, tx); err != nil {
		return ErrChallengeRequest
	}
	tag := i.epochTag()
	var keyID, storedTag []byte
	err := tx.QueryRowContext(ctx, `SELECT key_id,key_tag FROM auth_email_challenge_request_key_epoch WHERE slot=1 FOR UPDATE`).Scan(&keyID, &storedTag)
	if err == nil {
		if string(keyID) != i.keyID || !hmac.Equal(storedTag, tag[:]) {
			return ErrChallengeRequest
		}
		return i.validateRequestSchema(ctx, tx)
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return ErrChallengeRequest
	}
	if err := i.validateRequestSchema(ctx, tx); err != nil {
		return ErrChallengeRequest
	}
	var history []byte
	err = tx.QueryRowContext(ctx, `SELECT request_key_hmac FROM auth_email_challenge_request LIMIT 1 FOR UPDATE`).Scan(&history)
	if err == nil || !errors.Is(err, sql.ErrNoRows) {
		return ErrChallengeRequest
	}
	if _, err := tx.ExecContext(ctx, `INSERT INTO auth_email_challenge_request_key_epoch(slot,key_id,key_tag) VALUES (1,?,?)`, []byte(i.keyID), tag[:]); err != nil {
		return ErrChallengeRequest
	}
	var checkID, checkTag []byte
	if err := tx.QueryRowContext(ctx, `SELECT key_id,key_tag FROM auth_email_challenge_request_key_epoch WHERE slot=1 FOR UPDATE`).Scan(&checkID, &checkTag); err != nil || string(checkID) != i.keyID || !hmac.Equal(checkTag, tag[:]) {
		return ErrChallengeRequest
	}
	return nil
}

// Issue creates a challenge, its outbox row, and the protected retry result in
// one database transaction. A result is returned only after commit succeeds.
func (i *ChallengeRequestIssuer) Issue(ctx context.Context, db *sql.DB, input ChallengeRequestInput) (ChallengeRequestResult, error) {
	fail := func(err error) (ChallengeRequestResult, error) { return ChallengeRequestResult{}, err }
	if i == nil || ctx == nil || db == nil || i.challenges == nil || i.outbox == nil || i.identities == nil || i.limiter == nil {
		return fail(ErrChallengeRequest)
	}
	label := input.DeviceLabel
	if label != nil {
		copyLabel := *label
		label = &copyLabel
	}
	keyBytes, err := parseIdempotencyKey(input.IdempotencyKey)
	if err != nil {
		return fail(ErrChallengeRequest)
	}
	index, err := i.identities.Index(input.Email)
	if err != nil || index == [32]byte{} {
		return fail(ErrChallengeRequest)
	}
	fingerprint, err := domain.DeviceKeyFingerprint(input.DevicePublicKey)
	if err != nil || !validDeviceLabel(label) {
		return fail(ErrChallengeRequest)
	}
	if !input.TrustedSourceIP.IsValid() || input.TrustedSourceIP.IsUnspecified() || input.TrustedSourceIP.IsMulticast() || input.TrustedSourceIP.Zone() != "" {
		return fail(ErrChallengeRequest)
	}
	if err := i.limiter.Allow(ctx, ratelimit.EmailChallenge, ratelimit.Input{EmailIndex: index, DeviceFingerprint: fingerprint, SourceIP: input.TrustedSourceIP}); err != nil {
		if errors.Is(err, ratelimit.ErrLimited) {
			return fail(ErrChallengeRequestLimited)
		}
		return fail(ErrChallengeRequest)
	}
	keyHash := i.idempotencyHash(keyBytes)
	requestHash := i.requestHash(index, fingerprint, input.Email, label)
	candidateID, err := domain.GenerateChallengeID()
	if err != nil || !validChallengeID(candidateID) {
		return fail(ErrChallengeRequest)
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fail(ErrChallengeRequest)
	}
	defer tx.Rollback()
	epoch, err := i.outbox.LockEpochs(ctx, tx)
	if err != nil {
		return fail(ErrChallengeRequest)
	}
	if err := i.lockRequestEpoch(ctx, tx); err != nil {
		return fail(ErrChallengeRequest)
	}
	// The no-op duplicate update serializes the email slot without replacing an
	// existing active challenge. The candidate is CSPRNG-generated and the new
	// slot row rolls back unless challenge, outbox and retry record all commit.
	if _, err := tx.ExecContext(ctx, `INSERT INTO auth_email_login_slot(email_index,challenge_id) VALUES (?,?)
		ON DUPLICATE KEY UPDATE email_index=VALUES(email_index)`, index[:], []byte(candidateID)); err != nil {
		return fail(ErrChallengeRequest)
	}
	var activeRaw []byte
	if err := tx.QueryRowContext(ctx, `SELECT challenge_id FROM auth_email_login_slot WHERE email_index=? FOR UPDATE`, index[:]).Scan(&activeRaw); err != nil || len(activeRaw) == 0 {
		return fail(ErrChallengeRequest)
	}
	activeID := string(activeRaw)
	var oldRequestHash, oldChallengeID, oldCiphertext, oldKeyID []byte
	var oldExpiryText string
	lookupErr := tx.QueryRowContext(ctx, `SELECT request_hmac,challenge_id,response_enc,key_id,CAST(expires_at AS CHAR)
		FROM auth_email_challenge_request WHERE email_index=? AND request_key_hmac=? FOR UPDATE`, index[:], keyHash[:]).Scan(&oldRequestHash, &oldChallengeID, &oldCiphertext, &oldKeyID, &oldExpiryText)
	now, err := requestDatabaseTime(ctx, tx)
	if err != nil || now.IsZero() {
		return fail(ErrChallengeRequest)
	}
	if lookupErr == nil {
		expires, parseErr := parseRequestTime(oldExpiryText)
		if parseErr != nil || len(oldRequestHash) != 32 || len(oldChallengeID) == 0 || len(oldCiphertext) == 0 || string(oldKeyID) != i.keyID {
			return fail(ErrChallengeRequest)
		}
		if expires.After(now) {
			if !hmac.Equal(oldRequestHash, requestHash[:]) {
				return fail(ErrChallengeRequestConflict)
			}
			if activeID != string(oldChallengeID) {
				return fail(ErrChallengeRequestConflict)
			}
			body, err := i.replay(ctx, tx, index, keyHash, requestHash, string(oldChallengeID), oldCiphertext, expires)
			if err != nil {
				return fail(err)
			}
			if err := tx.Commit(); err != nil {
				return fail(ErrChallengeRequestUnknown)
			}
			return ChallengeRequestResult{body: body}, nil
		}
	} else if !errors.Is(lookupErr, sql.ErrNoRows) {
		return fail(ErrChallengeRequest)
	}
	challengeID := candidateID
	nonce, err := domain.GenerateChallengeNonce()
	if err != nil {
		return fail(ErrChallengeRequest)
	}
	code, err := i.outbox.deriver.Derive(challengeID, requestPurpose, i.codeDigits)
	if err != nil {
		return fail(ErrChallengeRequest)
	}
	if err := i.challenges.Issue(ctx, tx, challenge.IssueInput{Email: input.Email, ChallengeID: challengeID, Nonce: nonce, Code: code, PublicKey: input.DevicePublicKey}); err != nil {
		return fail(ErrChallengeRequest)
	}
	if err := i.outbox.Enqueue(ctx, tx, epoch, challengeID, i.codeDigits); err != nil {
		return fail(ErrChallengeRequest)
	}
	body, err := i.storeNew(ctx, tx, index, keyHash, requestHash, challengeID, lookupErr == nil)
	if err != nil {
		return fail(ErrChallengeRequest)
	}
	if err := tx.Commit(); err != nil {
		return fail(ErrChallengeRequestUnknown)
	}
	return ChallengeRequestResult{body: body}, nil
}

func (i *ChallengeRequestIssuer) lockRequestEpoch(ctx context.Context, tx *sql.Tx) error {
	var keyID, stored []byte
	if err := tx.QueryRowContext(ctx, `SELECT key_id,key_tag FROM auth_email_challenge_request_key_epoch WHERE slot=1 FOR SHARE`).Scan(&keyID, &stored); err != nil || string(keyID) != i.keyID {
		return ErrChallengeRequest
	}
	tag := i.epochTag()
	if !hmac.Equal(stored, tag[:]) {
		return ErrChallengeRequest
	}
	return nil
}

func (i *ChallengeRequestIssuer) validateRequestSchema(ctx context.Context, tx *sql.Tx) error {
	for _, query := range [...]string{
		`SELECT slot,key_id,key_tag FROM auth_email_challenge_request_key_epoch LIMIT 0`,
		`SELECT email_index,request_key_hmac,request_hmac,challenge_id,response_enc,key_id,created_at,expires_at FROM auth_email_challenge_request LIMIT 0`,
	} {
		rows, err := tx.QueryContext(ctx, query)
		if err != nil {
			return ErrChallengeRequest
		}
		if err := rows.Close(); err != nil || rows.Err() != nil {
			return ErrChallengeRequest
		}
	}
	return nil
}

func (i *ChallengeRequestIssuer) epochTag() [32]byte {
	var parts [3][32]byte
	for n, item := range []struct {
		key   []byte
		label string
	}{
		{i.idemKey[:], "idempotency"}, {i.requestKey[:], "request"}, {i.cipherKey[:], "response"},
	} {
		mac := hmac.New(sha256.New, item.key)
		_, _ = io.WriteString(mac, requestEpochDomain)
		writeRequestPart(mac, []byte(item.label))
		copy(parts[n][:], mac.Sum(nil))
	}
	h := sha256.New()
	writeRequestPart(h, []byte(requestEpochDomain))
	writeRequestPart(h, []byte(i.keyID))
	for n := range parts {
		writeRequestPart(h, parts[n][:])
	}
	var tag [32]byte
	copy(tag[:], h.Sum(nil))
	return tag
}

func (i *ChallengeRequestIssuer) idempotencyHash(key []byte) [32]byte {
	mac := hmac.New(sha256.New, i.idemKey[:])
	_, _ = io.WriteString(mac, requestKeyDomain)
	writeRequestPart(mac, key)
	var out [32]byte
	copy(out[:], mac.Sum(nil))
	return out
}

func (i *ChallengeRequestIssuer) requestHash(index, fingerprint [32]byte, email string, label *string) [32]byte {
	mac := hmac.New(sha256.New, i.requestKey[:])
	_, _ = io.WriteString(mac, requestHashDomain)
	writeRequestPart(mac, []byte(requestMethod))
	writeRequestPart(mac, []byte(requestRoute))
	writeRequestPart(mac, []byte(requestPurpose))
	writeRequestPart(mac, index[:])
	// Hash semantic fields in a fixed order, not raw JSON bytes. The original
	// email spelling remains part of retry equality even when normalization
	// maps multiple accepted spellings to the same protected lookup index.
	writeRequestPart(mac, []byte(email))
	writeRequestPart(mac, fingerprint[:])
	if label == nil {
		writeRequestPart(mac, []byte{0})
	} else {
		writeRequestPart(mac, []byte{1})
		writeRequestPart(mac, []byte(*label))
	}
	var out [32]byte
	copy(out[:], mac.Sum(nil))
	return out
}

func (i *ChallengeRequestIssuer) replay(ctx context.Context, tx *sql.Tx, index, keyHash, requestHash [32]byte, challengeID string, encrypted []byte, requestExpires time.Time) ([]byte, error) {
	meta, err := i.outbox.lockChallenge(ctx, tx, challengeID)
	if err != nil || meta.index != index {
		return nil, ErrChallengeRequestConflict
	}
	var attempts, maxAttempts int
	var nonce string
	if err := tx.QueryRowContext(ctx, `SELECT attempts,max_attempts,nonce FROM auth_email_login_challenge WHERE challenge_id=? FOR UPDATE`, []byte(challengeID)).Scan(&attempts, &maxAttempts, &nonce); err != nil || maxAttempts < 1 || attempts >= maxAttempts {
		return nil, ErrChallengeRequestConflict
	}
	var digits int
	if err := tx.QueryRowContext(ctx, `SELECT code_digits FROM auth_email_outbox WHERE challenge_id=? FOR UPDATE`, []byte(challengeID)).Scan(&digits); err != nil || digits < 6 || digits > 10 || i.outbox.validateChallenge(meta, challengeID, digits) != nil {
		return nil, ErrChallengeRequestConflict
	}
	body, err := i.decrypt(index, keyHash, requestHash, challengeID, encrypted)
	if err != nil {
		return nil, ErrChallengeRequest
	}
	var response struct {
		ChallengeID string `json:"challengeId"`
		Nonce       string `json:"nonce"`
		ExpiresAt   string `json:"expiresAt"`
	}
	decoder := json.NewDecoder(bytes.NewReader(body))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&response); err != nil || response.ChallengeID != challengeID || response.Nonce != nonce || !validNonce(response.Nonce) {
		return nil, ErrChallengeRequest
	}
	var trailing any
	if err := decoder.Decode(&trailing); err != io.EOF {
		return nil, ErrChallengeRequest
	}
	expires, err := parseRequestTime(response.ExpiresAt)
	if err != nil || !expires.Equal(meta.expires) {
		return nil, ErrChallengeRequest
	}
	// Recheck both server-side deadlines after acquiring every row lock and
	// completing decryption, immediately before the caller commits the replay.
	finalNow, err := requestDatabaseTime(ctx, tx)
	if err != nil || !requestExpires.After(finalNow) || !meta.expires.After(finalNow) {
		return nil, ErrChallengeRequestConflict
	}
	return body, nil
}

func (i *ChallengeRequestIssuer) encrypt(index, keyHash, requestHash [32]byte, challengeID string, body []byte) ([]byte, error) {
	block, err := aes.NewCipher(i.cipherKey[:])
	if err != nil {
		return nil, ErrChallengeRequest
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, ErrChallengeRequest
	}
	nonce := make([]byte, aead.NonceSize())
	if _, err := io.ReadFull(rand.Reader, nonce); err != nil {
		return nil, ErrChallengeRequest
	}
	out := append([]byte{1}, nonce...)
	out = aead.Seal(out, nonce, body, requestAAD(i.keyID, index, keyHash, requestHash, challengeID))
	if len(out) > maxRequestResponse {
		return nil, ErrChallengeRequest
	}
	return out, nil
}

func (i *ChallengeRequestIssuer) decrypt(index, keyHash, requestHash [32]byte, challengeID string, encrypted []byte) ([]byte, error) {
	block, err := aes.NewCipher(i.cipherKey[:])
	if err != nil || len(encrypted) < 1+12+16 || encrypted[0] != 1 {
		return nil, ErrChallengeRequest
	}
	aead, err := cipher.NewGCM(block)
	if err != nil || len(encrypted) < 1+aead.NonceSize()+aead.Overhead() {
		return nil, ErrChallengeRequest
	}
	nonce := encrypted[1 : 1+aead.NonceSize()]
	plain, err := aead.Open(nil, nonce, encrypted[1+aead.NonceSize():], requestAAD(i.keyID, index, keyHash, requestHash, challengeID))
	if err != nil || len(plain) == 0 || len(plain) > 1024 {
		return nil, ErrChallengeRequest
	}
	return plain, nil
}

func requestAAD(keyID string, index, keyHash, requestHash [32]byte, challengeID string) []byte {
	var out []byte
	out = append(out, requestAADDomain...)
	for _, part := range [][]byte{[]byte(keyID), index[:], keyHash[:], requestHash[:], []byte(challengeID)} {
		var size [4]byte
		binary.BigEndian.PutUint32(size[:], uint32(len(part)))
		out = append(out, size[:]...)
		out = append(out, part...)
	}
	return out
}

func parseIdempotencyKey(value string) ([]byte, error) {
	if len(value) < 22 || len(value) > 128 {
		return nil, ErrChallengeRequest
	}
	decoded, err := base64.RawURLEncoding.Strict().DecodeString(value)
	if err != nil || len(decoded) < 16 || base64.RawURLEncoding.EncodeToString(decoded) != value {
		return nil, ErrChallengeRequest
	}
	return decoded, nil
}

func validDeviceLabel(value *string) bool {
	if value == nil {
		return true
	}
	return utf8.ValidString(*value) && utf8.RuneCountInString(*value) >= 1 && utf8.RuneCountInString(*value) <= 80
}

func validNonce(value string) bool {
	decoded, err := base64.RawURLEncoding.Strict().DecodeString(value)
	return err == nil && len(decoded) == 32 && base64.RawURLEncoding.EncodeToString(decoded) == value
}

func requestDatabaseTime(ctx context.Context, tx *sql.Tx) (time.Time, error) {
	var raw string
	if err := tx.QueryRowContext(ctx, `SELECT CAST(UTC_TIMESTAMP(6) AS CHAR)`).Scan(&raw); err != nil {
		return time.Time{}, ErrChallengeRequest
	}
	return parseRequestTime(raw)
}

func parseRequestTime(value string) (time.Time, error) {
	parsed, err := time.Parse("2006-01-02 15:04:05.999999", value)
	if err == nil {
		return parsed.UTC(), nil
	}
	parsed, err = time.Parse(time.RFC3339Nano, value)
	return parsed.UTC(), err
}

func writeRequestPart(dst hash.Hash, value []byte) {
	var size [4]byte
	binary.BigEndian.PutUint32(size[:], uint32(len(value)))
	_, _ = dst.Write(size[:])
	_, _ = dst.Write(value)
}

type requestResponse struct {
	ChallengeID string `json:"challengeId"`
	Nonce       string `json:"nonce"`
	ExpiresAt   string `json:"expiresAt"`
}

func (i *ChallengeRequestIssuer) responseFor(ctx context.Context, tx *sql.Tx, id string) ([]byte, error) {
	var nonce, expiresText string
	if err := tx.QueryRowContext(ctx, `SELECT nonce,CAST(expires_at AS CHAR) FROM auth_email_login_challenge WHERE challenge_id=?`, []byte(id)).Scan(&nonce, &expiresText); err != nil {
		return nil, ErrChallengeRequest
	}
	expires, err := parseRequestTime(expiresText)
	if err != nil || !validNonce(nonce) {
		return nil, ErrChallengeRequest
	}
	body, err := json.Marshal(requestResponse{ChallengeID: id, Nonce: nonce, ExpiresAt: expires.Format(time.RFC3339Nano)})
	if err != nil || len(body) > 1024 {
		return nil, ErrChallengeRequest
	}
	return body, nil
}

func (i *ChallengeRequestIssuer) storeNew(ctx context.Context, tx *sql.Tx, index, keyHash, requestHash [32]byte, id string, old bool) ([]byte, error) {
	body, err := i.responseFor(ctx, tx, id)
	if err != nil {
		return nil, err
	}
	encrypted, err := i.encrypt(index, keyHash, requestHash, id, body)
	if err != nil {
		return nil, err
	}
	now, err := requestDatabaseTime(ctx, tx)
	if err != nil || now.IsZero() {
		return nil, ErrChallengeRequest
	}
	var response requestResponse
	if err := json.Unmarshal(body, &response); err != nil {
		return nil, ErrChallengeRequest
	}
	challengeExpires, err := parseRequestTime(response.ExpiresAt)
	if err != nil || !challengeExpires.After(now) {
		return nil, ErrChallengeRequest
	}
	now = now.UTC().Truncate(time.Microsecond)
	expires := now.Add(i.retention)
	if !expires.After(now) {
		return nil, ErrChallengeRequest
	}
	var result sql.Result
	if old {
		result, err = tx.ExecContext(ctx, `UPDATE auth_email_challenge_request SET request_hmac=?,challenge_id=?,response_enc=?,key_id=?,created_at=?,expires_at=?
			WHERE email_index=? AND request_key_hmac=?`, requestHash[:], []byte(id), encrypted, []byte(i.keyID), sqlUTC(now), sqlUTC(expires), index[:], keyHash[:])
	} else {
		result, err = tx.ExecContext(ctx, `INSERT INTO auth_email_challenge_request(email_index,request_key_hmac,request_hmac,challenge_id,response_enc,key_id,created_at,expires_at)
			VALUES (?,?,?,?,?,?,?,?)`, index[:], keyHash[:], requestHash[:], []byte(id), encrypted, []byte(i.keyID), sqlUTC(now), sqlUTC(expires))
	}
	if err != nil {
		return nil, ErrChallengeRequest
	}
	if old {
		if changed, err := result.RowsAffected(); err != nil || changed != 1 {
			return nil, ErrChallengeRequest
		}
	}
	return body, nil
}
